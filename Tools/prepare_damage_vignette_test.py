"""Temporary PIE scene for the actual local-player damage path."""
import unreal as u
editor = u.get_editor_subsystem(u.LevelEditorSubsystem)
assert not editor.is_in_play_in_editor()
assert not u.EditorLoadingAndSavingUtils.get_dirty_map_packages()
assert not u.EditorLoadingAndSavingUtils.get_dirty_content_packages()
world = u.EditorLoadingAndSavingUtils.new_blank_map(False)
world.get_world_settings().set_editor_property('default_game_mode', u.LOL_GameModeBase)
actors = u.get_editor_subsystem(u.EditorActorSubsystem)
for name, location in [('VignetteVictim', u.Vector(0, 0, 100)), ('VignetteOther', u.Vector(700, 0, 100))]:
    actor = actors.spawn_actor_from_class(u.Champion_Ezreal, location)
    actor.set_actor_label(name)
    actor.set_editor_property('tags', [name])
    actor.set_editor_property('auto_possess_ai', u.AutoPossessAI.DISABLED)
    actor.character_movement.set_movement_mode(u.MovementMode.MOVE_NONE)
position = u.Vector(0, -750, 700)
actors.spawn_actor_from_class(u.CameraActor, position, u.MathLibrary.find_look_at_rotation(position, u.Vector(0, 0, 80)))
actors.spawn_actor_from_class(u.DirectionalLight, u.Vector(0, 0, 700), u.Rotator(pitch=-60, yaw=-30, roll=0))
floor = actors.spawn_actor_from_class(u.StaticMeshActor, u.Vector(0, 0, -30))
floor.static_mesh_component.set_static_mesh(u.load_asset('/Engine/BasicShapes/Plane'))
floor.set_actor_scale3d(u.Vector(40, 40, 1))
perf = u.get_default_object(u.load_class(None, '/Script/UnrealEd.EditorPerformanceSettings'))
perf.set_editor_property('bThrottleCPUWhenNotForeground', False)
editor.editor_request_begin_play()
print('DAMAGE_VIGNETTE_PIE_REQUESTED')
