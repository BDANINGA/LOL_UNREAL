"""Unsaved scene for the actual champion recall path. Requires a clean editor."""
import unreal as u

editor = u.get_editor_subsystem(u.LevelEditorSubsystem)
assert not editor.is_in_play_in_editor()
assert not u.EditorLoadingAndSavingUtils.get_dirty_map_packages()
assert not u.EditorLoadingAndSavingUtils.get_dirty_content_packages()
world = u.EditorLoadingAndSavingUtils.new_blank_map(False)
world.get_world_settings().set_editor_property('default_game_mode', u.GameModeBase)
actors = u.get_editor_subsystem(u.EditorActorSubsystem)
position = u.Vector(600, -850, 950)
camera = actors.spawn_actor_from_class(u.CameraActor, position, u.MathLibrary.find_look_at_rotation(position, u.Vector(0, 0, 65)))
camera.camera_component.set_field_of_view(45)
actors.spawn_actor_from_class(u.DirectionalLight, u.Vector(0, 0, 700), u.Rotator(pitch=-55, yaw=-30, roll=0))
floor = actors.spawn_actor_from_class(u.StaticMeshActor, u.Vector(0, 0, -2))
floor.static_mesh_component.set_static_mesh(u.load_asset('/Engine/BasicShapes/Plane'))
floor.set_actor_scale3d(u.Vector(80, 80, 1))
material = u.AssetToolsHelpers.get_asset_tools().create_asset('M_RecallTestFloor', '/Game/Developers/RecallPreview', u.Material, u.MaterialFactoryNew())
color = u.MaterialEditingLibrary.create_material_expression(material, u.MaterialExpressionConstant3Vector)
color.set_editor_property('constant', u.LinearColor(0.025, 0.035, 0.05, 1))
u.MaterialEditingLibrary.connect_material_property(color, '', u.MaterialProperty.MP_BASE_COLOR)
u.MaterialEditingLibrary.recompile_material(material)
floor.static_mesh_component.set_material(0, material)
for i, name in enumerate(['RecallComplete', 'RecallCancel', 'RecallDamage', 'RecallDeath']):
    champion = actors.spawn_actor_from_class(u.Champion_Ezreal, u.Vector(0, i * 1500, 132))
    champion.set_actor_label(name)
    champion.set_editor_property('tags', [name])
    champion.set_editor_property('auto_possess_ai', u.AutoPossessAI.DISABLED)
perf = u.get_default_object(u.load_class(None, '/Script/UnrealEd.EditorPerformanceSettings'))
perf.set_editor_property('bThrottleCPUWhenNotForeground', False)
editor.editor_request_begin_play()
